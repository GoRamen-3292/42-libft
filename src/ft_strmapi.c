#include "libft.h"

char	*ft_strmapi(const char *s, char (*f)(unsigned int, char))
{
	const unsigned int	s_len = ft_strlen(s);
	unsigned int		i;
	char				*result;

	i = 0;
	result = malloc(sizeof(char) * (s_len + 1));
	if (result == NULL)
		return (NULL);
	while (i < s_len)
	{
		result[i] = f(i, s[i]);
		i++;
	}
	result[i] = '\0';
	return (result);
}
