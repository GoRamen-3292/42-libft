#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	char	*result;

	if (nmemb * size == 0)
		return (malloc(0));
	result = malloc(nmemb * size);
	if (result == NULL)
		return (NULL);
	ft_bzero(result, nmemb * size);
	return (result);
}
